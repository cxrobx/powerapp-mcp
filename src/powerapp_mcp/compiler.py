"""Compiler — transforms AppState into a .msapp ZIP file."""

from __future__ import annotations

import io
import json
import zipfile
from datetime import datetime, timezone

from .checksum import compute_file_checksums
from .models import AppState, Control
from .properties import generate_properties
from .templates import get_used_templates
from .themes import generate_themes_json


def _serialize_control(control: Control) -> dict:
    """Serialize a Control tree to the .msapp JSON format."""
    rules = []
    for r in control.Rules:
        rules.append({
            "Property": r.Property,
            "Category": r.Category,
            "InvariantScript": r.InvariantScript,
            "RuleProviderType": r.RuleProviderType,
        })

    template = {
        "Id": control.Template.Id,
        "Version": control.Template.Version,
        "LastModifiedTimestamp": control.Template.LastModifiedTimestamp,
        "Name": control.Template.Name,
        "FirstParty": control.Template.FirstParty,
        "IsPremiumPcfControl": control.Template.IsPremiumPcfControl,
        "IsCustomGroupControlTemplate": control.Template.IsCustomGroupControlTemplate,
        "CustomGroupControlTemplateName": control.Template.CustomGroupControlTemplateName,
        "IsComponentDefinition": control.Template.IsComponentDefinition,
        "OverridableProperties": control.Template.OverridableProperties,
    }
    if control.Template.ComponentType:
        template["ComponentType"] = control.Template.ComponentType
    if control.Template.CustomProperties:
        template["CustomProperties"] = control.Template.CustomProperties
    if control.Template.HostType:
        template["HostType"] = control.Template.HostType

    children = [_serialize_control(c) for c in control.Children]

    return {
        "Type": control.Type,
        "Name": control.Name,
        "HasDynamicProperties": control.HasDynamicProperties,
        "Template": template,
        "Index": control.Index,
        "PublishOrderIndex": control.PublishOrderIndex,
        "VariantName": control.VariantName,
        "LayoutName": control.LayoutName,
        "MetaDataIDKey": control.MetaDataIDKey,
        "PersistMetaDataIDKey": control.PersistMetaDataIDKey,
        "IsFromScreenLayout": control.IsFromScreenLayout,
        "StyleName": control.StyleName,
        "Parent": control.Parent,
        "IsDataControl": control.IsDataControl,
        "AllowAccessToGlobals": control.AllowAccessToGlobals,
        "IsGroupControl": control.IsGroupControl,
        "IsAutoGenerated": control.IsAutoGenerated,
        "Rules": rules,
        "ControlPropertyState": control.ControlPropertyState,
        "IsLocked": control.IsLocked,
        "ControlUniqueId": control.ControlUniqueId,
        "Children": children,
    }


def _collect_control_types(control: Control) -> set[str]:
    """Recursively collect all template names used."""
    types = {control.Template.Name}
    for child in control.Children:
        types.update(_collect_control_types(child))
    return types


def compile_msapp(state: AppState) -> bytes:
    """Compile the AppState into .msapp ZIP bytes.

    Returns the ZIP file contents as bytes.
    """
    files: dict[str, bytes] = {}

    # 1. Header.json
    header = {
        "DocVersion": state.doc_version,
        "MinVersionToLoad": state.min_version,
        "MSAppStructureVersion": "2.0",
        "LastSavedDateTimeUTC": datetime.now(timezone.utc).strftime("%m/%d/%Y %H:%M:%S"),
    }
    files["Header.json"] = _to_json_bytes(header)

    # 2. Properties.json
    props = generate_properties(state)
    files["Properties.json"] = _to_json_bytes(props)

    # 3. Controls/
    # 3a. App host control (always Controls/1.json)
    if state.app_control:
        app_doc = {"TopParent": _serialize_control(state.app_control)}
        files["Controls\\1.json"] = _to_json_bytes(app_doc)

    # 3b. Screen controls
    for screen in state.screens:
        screen_doc = {"TopParent": _serialize_control(screen)}
        uid = screen.ControlUniqueId
        files[f"Controls\\{uid}.json"] = _to_json_bytes(screen_doc)

    # 4. Components/
    for comp in state.components:
        comp_doc = {"TopParent": _serialize_control(comp)}
        uid = comp.ControlUniqueId
        files[f"Components\\{uid}.json"] = _to_json_bytes(comp_doc)

    # 5. ComponentsMetadata.json
    if state.components_metadata:
        cm_list = [m.model_dump() for m in state.components_metadata]
    else:
        cm_list = []
    files["ComponentsMetadata.json"] = _to_json_bytes(cm_list)

    # 6. References/
    # 6a. DataSources.json
    ds_list = [ds.model_dump() for ds in state.data_sources]
    files["References\\DataSources.json"] = _to_json_bytes({"DataSources": ds_list})

    # 6b. Templates.json — collect used control types
    used_types: set[str] = set()
    for screen in state.screens:
        used_types.update(_collect_control_types(screen))
    for comp in state.components:
        used_types.update(_collect_control_types(comp))
    # Remove non-template types
    used_types.discard("screen")
    used_types.discard("appinfo")

    used_templates = get_used_templates(used_types)
    files["References\\Templates.json"] = _to_json_bytes({"UsedTemplates": used_templates})

    # 6c. Themes.json
    themes_data = generate_themes_json(state.theme)
    files["References\\Themes.json"] = _to_json_bytes(themes_data)

    # 6d. Resources.json
    files["References\\Resources.json"] = _to_json_bytes({"Resources": []})

    # 6e. AuxDataMap.json
    files["References\\AuxDataMap.json"] = _to_json_bytes({
        "AppFromDataMetaDataIdsToEntityNameMappings": "{}",
    })

    # 7. checksum.json
    checksum_data = compute_file_checksums(files)
    files["checksum.json"] = _to_json_bytes(checksum_data)

    # 8. Write everything into a ZIP
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for path, data in sorted(files.items()):
            zf.writestr(path, data)

    return buf.getvalue()


def _to_json_bytes(obj: dict | list) -> bytes:
    """Serialize to JSON bytes with consistent formatting."""
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
