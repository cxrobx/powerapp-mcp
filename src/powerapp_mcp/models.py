"""Pydantic models for the Power Apps .msapp format."""

from __future__ import annotations

import uuid
from typing import Literal

from pydantic import BaseModel, Field


class Rule(BaseModel):
    """A property rule on a control — maps to one entry in the Rules array."""

    Property: str
    Category: Literal["Data", "Design", "Behavior", "ConstantData"]
    InvariantScript: str
    RuleProviderType: Literal["Unknown", "System", "User"] = "Unknown"


class Template(BaseModel):
    """Control template definition."""

    Id: str  # e.g., "http://microsoft.com/appmagic/button"
    Version: str  # e.g., "2.2.0"
    LastModifiedTimestamp: str = "0"
    Name: str  # e.g., "button"
    FirstParty: bool = True
    IsPremiumPcfControl: bool = False
    IsCustomGroupControlTemplate: bool = False
    CustomGroupControlTemplateName: str = ""
    IsComponentDefinition: bool = False
    ComponentType: str | None = None
    OverridableProperties: dict = Field(default_factory=dict)
    CustomProperties: list = Field(default_factory=list)
    HostType: str | None = None


class Control(BaseModel):
    """A control node in the app tree. Screens and child controls share this structure."""

    Type: Literal["ControlInfo"] = "ControlInfo"
    Name: str
    HasDynamicProperties: bool = False
    Template: Template
    Index: float = 0.0
    PublishOrderIndex: int = 0
    VariantName: str = ""
    LayoutName: str = ""
    MetaDataIDKey: str = ""
    PersistMetaDataIDKey: bool = False
    IsFromScreenLayout: bool = False
    StyleName: str = ""
    Parent: str = ""
    IsDataControl: bool = False
    AllowAccessToGlobals: bool = True
    IsGroupControl: bool = False
    IsAutoGenerated: bool = False
    Rules: list[Rule] = Field(default_factory=list)
    ControlPropertyState: list[str | dict] = Field(default_factory=list)
    IsLocked: bool = False
    ControlUniqueId: str = ""
    Children: list[Control] = Field(default_factory=list)

    def find_control(self, name: str) -> Control | None:
        """Recursively find a control by name in this subtree."""
        if self.Name == name:
            return self
        for child in self.Children:
            found = child.find_control(name)
            if found:
                return found
        return None


class ThemePaletteEntry(BaseModel):
    """A single color in the theme palette."""

    name: str
    value: str
    type: str = "c"


class ThemeDefinition(BaseModel):
    """A named theme with a color palette."""

    name: str = "defaultTheme"
    palette: list[ThemePaletteEntry] = Field(default_factory=list)


class DataSource(BaseModel):
    """A configured data source connection."""

    Name: str
    IsSampleData: bool = False
    IsWritable: bool = True
    Type: str = "ConnectedDataSourceInfo"
    DatasetName: str = ""
    TableName: str = ""
    ApiId: str = ""
    EncodeDataset: bool = True
    DataEntityMetadataJson: str = "{}"
    CdpRevision: dict = Field(default_factory=lambda: {
        "RevisionNumber": 1,
        "BaseUrl": "/",
        "LastChangedTimeString": "",
    })


class ConnectionReference(BaseModel):
    """A connection reference in Properties.json LocalConnectionReferences."""

    id: str = ""
    connectionInstanceId: str = ""
    dataSources: list[str] = Field(default_factory=list)
    datasets: dict = Field(default_factory=dict)
    dependencies: dict = Field(default_factory=dict)
    dependents: list = Field(default_factory=list)
    connectionRef: dict = Field(default_factory=dict)


class ComponentMetadata(BaseModel):
    """Metadata for a custom component."""

    TemplateName: str
    ComponentName: str
    Description: str = ""
    AllowCustomization: bool = True
    AllowAccessToGlobals: bool = False


class AppState(BaseModel):
    """The full in-memory state of a Power App being constructed."""

    name: str = "New App"
    app_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    doc_version: str = "1.332"
    min_version: str = "1.331"
    app_type: str = "Tablet"  # Phone, Tablet, Desktop
    width: int = 1366
    height: int = 768
    orientation: str = "landscape"

    # The App host control (Controls/1.json)
    app_control: Control | None = None

    # Screens (each is a Control with Template.Name == "screen")
    screens: list[Control] = Field(default_factory=list)

    # Data sources
    data_sources: list[DataSource] = Field(default_factory=list)
    connection_references: dict[str, ConnectionReference] = Field(default_factory=dict)

    # Theme
    theme: ThemeDefinition = Field(default_factory=ThemeDefinition)

    # Components
    components: list[Control] = Field(default_factory=list)
    components_metadata: list[ComponentMetadata] = Field(default_factory=list)

    # Internal counters
    next_id: int = 1
    next_index: float = 1.0
    name_counters: dict[str, int] = Field(default_factory=dict)

    def allocate_id(self) -> str:
        """Get the next unique control ID and increment."""
        uid = str(self.next_id)
        self.next_id += 1
        return uid

    def allocate_index(self) -> float:
        """Get the next z-index and increment."""
        idx = self.next_index
        self.next_index += 1.0
        return idx

    def auto_name(self, control_type: str) -> str:
        """Generate an auto-incremented name like 'Button1', 'Label2'."""
        # Capitalize first letter for the name
        base = control_type[0].upper() + control_type[1:]
        count = self.name_counters.get(control_type, 0) + 1
        self.name_counters[control_type] = count
        return f"{base}{count}"

    def find_control(self, name: str) -> Control | None:
        """Find a control by name across all screens."""
        for screen in self.screens:
            found = screen.find_control(name)
            if found:
                return found
        return None

    def find_screen(self, name: str) -> Control | None:
        """Find a screen by name."""
        for screen in self.screens:
            if screen.Name == name:
                return screen
        return None

    def count_controls_by_type(self) -> dict[str, int]:
        """Count controls by template name for Properties.json ControlCount."""
        counts: dict[str, int] = {}

        def _count(control: Control) -> None:
            tname = control.Template.Name
            counts[tname] = counts.get(tname, 0) + 1
            for child in control.Children:
                _count(child)

        for screen in self.screens:
            _count(screen)
        for comp in self.components:
            _count(comp)
        return counts
